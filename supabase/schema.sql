begin;

create table if not exists public.artworks (
  id bigint generated by default as identity primary key,
  title text not null,
  description text not null default '',
  tags text[] not null default '{}',
  image_path text not null,
  width integer not null check (width > 0),
  height integer not null check (height > 0),
  created_at timestamptz not null default now()
);

create index if not exists artworks_created_at_idx
  on public.artworks (created_at desc);

create index if not exists artworks_tags_idx
  on public.artworks using gin (tags);

create table if not exists public.site_settings (
  id smallint primary key check (id = 1),
  commissions_open boolean not null default false,
  updated_at timestamptz not null default now()
);

insert into public.site_settings (id, commissions_open)
values (1, false)
on conflict (id) do nothing;

create table if not exists public.admins (
  user_id uuid primary key references auth.users (id) on delete cascade,
  created_at timestamptz not null default now()
);

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.admins
    where user_id = (select auth.uid())
  );
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to authenticated;

create or replace function public.get_artwork_tags()
returns table (tag text)
language sql
stable
security invoker
set search_path = ''
as $$
  select distinct unnest(artworks.tags) as tag
  from public.artworks
  where cardinality(artworks.tags) > 0
  order by tag;
$$;

grant execute on function public.get_artwork_tags() to anon, authenticated;

alter table public.artworks enable row level security;
alter table public.site_settings enable row level security;
alter table public.admins enable row level security;

drop policy if exists "Public can read artworks" on public.artworks;
create policy "Public can read artworks"
  on public.artworks
  for select
  to anon, authenticated
  using (true);

drop policy if exists "Admins can manage artworks" on public.artworks;
create policy "Admins can manage artworks"
  on public.artworks
  for all
  to authenticated
  using (public.is_admin())
  with check (public.is_admin());

drop policy if exists "Public can read site settings" on public.site_settings;
create policy "Public can read site settings"
  on public.site_settings
  for select
  to anon, authenticated
  using (true);

drop policy if exists "Admins can manage site settings" on public.site_settings;
create policy "Admins can manage site settings"
  on public.site_settings
  for all
  to authenticated
  using (public.is_admin())
  with check (public.is_admin());

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'artworks',
  'artworks',
  true,
  10485760,
  array['image/jpeg', 'image/png', 'image/webp']
)
on conflict (id) do update
set
  public = excluded.public,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "Public can read artwork files" on storage.objects;
create policy "Public can read artwork files"
  on storage.objects
  for select
  to anon, authenticated
  using (bucket_id = 'artworks');

drop policy if exists "Admins can upload artwork files" on storage.objects;
create policy "Admins can upload artwork files"
  on storage.objects
  for insert
  to authenticated
  with check (bucket_id = 'artworks' and public.is_admin());

drop policy if exists "Admins can update artwork files" on storage.objects;
create policy "Admins can update artwork files"
  on storage.objects
  for update
  to authenticated
  using (bucket_id = 'artworks' and public.is_admin())
  with check (bucket_id = 'artworks' and public.is_admin());

drop policy if exists "Admins can delete artwork files" on storage.objects;
create policy "Admins can delete artwork files"
  on storage.objects
  for delete
  to authenticated
  using (bucket_id = 'artworks' and public.is_admin());

commit;
